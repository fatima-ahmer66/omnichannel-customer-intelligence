CREATE OR REPLACE WAREHOUSE ECOMMERCE_DW_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE;

CREATE OR REPLACE DATABASE ECOMMERCE_DW_DB;
CREATE OR REPLACE SCHEMA ECOMMERCE_DW_DB.WAREHOUSE;

USE WAREHOUSE ECOMMERCE_DW_WH;
USE DATABASE ECOMMERCE_DW_DB;
USE SCHEMA WAREHOUSE;

CREATE OR REPLACE FILE FORMAT ECOMMERCE_CSV_FMT
    TYPE = CSV
    FIELD_DELIMITER = ','
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    NULL_IF = ('', 'NULL', 'null', 'None')
    EMPTY_FIELD_AS_NULL = TRUE;

CREATE OR REPLACE STAGE ECOMMERCE_STAGE;