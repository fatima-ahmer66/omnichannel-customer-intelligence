USE WAREHOUSE ECOMMERCE_DW_WH;
USE DATABASE ECOMMERCE_DW_DB;
USE SCHEMA WAREHOUSE;

CREATE OR REPLACE TABLE DIM_CUSTOMER (
    CUSTOMER_KEY NUMBER(38,0) NOT NULL,
    CUSTOMER_ID VARCHAR(50) NOT NULL,
    CUSTOMER_AGE NUMBER(3,0),
    CUSTOMER_GENDER VARCHAR(20),
    AGE_GROUP VARCHAR(20)
);

CREATE OR REPLACE TABLE DIM_PRODUCT (
    PRODUCT_KEY NUMBER(38,0) NOT NULL,
    PRODUCT_ID VARCHAR(50) NOT NULL,
    CATEGORY VARCHAR(50),
    STANDARD_PRICE NUMBER(10,2)
);

CREATE OR REPLACE TABLE DIM_CHANNEL_REGION (
    CHANNEL_REGION_KEY NUMBER(38,0) NOT NULL,
    REGION VARCHAR(50),
    PAYMENT_METHOD VARCHAR(30),
    CHANNEL_TYPE VARCHAR(30)
);

CREATE OR REPLACE TABLE DIM_DATE (
    DATE_KEY NUMBER(8,0) NOT NULL,
    FULL_DATE DATE NOT NULL,
    YEAR NUMBER(4,0),
    QUARTER NUMBER(1,0),
    MONTH NUMBER(2,0),
    MONTH_NAME VARCHAR(20),
    DAY NUMBER(2,0),
    DAY_NAME VARCHAR(15),
    IS_WEEKEND NUMBER(1,0)
);

CREATE OR REPLACE TABLE FACT_SALES (
    SALES_KEY NUMBER(38,0) NOT NULL,
    ORDER_ID VARCHAR(50) NOT NULL,
    CUSTOMER_KEY NUMBER(38,0),
    PRODUCT_KEY NUMBER(38,0),
    CHANNEL_REGION_KEY NUMBER(38,0),
    DATE_KEY NUMBER(8,0),
    QUANTITY NUMBER(10,0),
    PRICE NUMBER(10,2),
    DISCOUNT NUMBER(6,2),
    GROSS_AMOUNT NUMBER(12,2),
    DISCOUNT_AMOUNT NUMBER(12,2),
    NET_SALES_BEFORE_SHIPPING NUMBER(12,2),
    SHIPPING_COST NUMBER(10,2),
    TOTAL_AMOUNT NUMBER(12,2),
    PROFIT_MARGIN NUMBER(10,2),
    DELIVERY_TIME_DAYS NUMBER(5,0),
    IS_RETURNED NUMBER(1,0)
);